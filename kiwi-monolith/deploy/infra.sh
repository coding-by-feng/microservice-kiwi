# ==================== Main Entry Point ====================

main() {
    local cmd="${1:-}"

    # Commands that don't need prerequisites check
    case "$cmd" in
        help|-h|--help)
            show_help
            exit 0
            ;;
        "")
            show_help
            exit 1
            ;;
    esac

    # Check prerequisites for all other commands
    check_prerequisites

    # Load environment
    load_env
    init_backup_dir

    # Execute command
    case "$cmd" in
        setup)
            setup_infrastructure "$@"
            ;;
        start)
            start_infra
            ;;
        stop)
            stop_infra
            ;;
        restart)
            restart_infra
            ;;
        status)
            show_status
            ;;
        logs)
            show_logs "$@"
            ;;
        clean)
            clean_infra
            ;;
        backup-db)
            backup_db
            ;;
        restore-db)
            restore_db "$@"
            ;;
        backup-ftp)
            backup_ftp
            ;;
        restore-ftp)
            restore_ftp "$@"
            ;;
        backups)
            list_backups
            ;;
        *)
            log_error "Unknown command: $cmd"
            echo ""
            show_help
            exit 1
            ;;
    esac
}

# Run main function
main "$@"
